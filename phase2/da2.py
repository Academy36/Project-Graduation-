        def classify_hhi(val):
            if val >= 0.6: return "High Monopoly"
            elif val >= 0.4: return "Moderate Monopoly"
            else: return "Highly Competitive"

        df_me['Structure'] = df_me['Concentration of supplying countries'].apply(classify_hhi)

