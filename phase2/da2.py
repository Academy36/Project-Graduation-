if df_raw is not None:

    df_me = df_raw[df_raw['Region'].str.contains('Middle East', case=False, na=False)].copy()


    med_val = df_me['Value imported in 2024 (USD thousand)'].median()
    med_grow = df_me['Annual growth in value between 2020-2024 (%)'].median()
    med_hhi = df_me['Concentration of supplying countries'].median()


    col1, col2, col3, col4 = st.columns(4)
    with col1:
        total_import = df_me['Value imported in 2024 (USD thousand)'].sum()
